document.addEventListener('DOMContentLoaded', function() {
    // This function is debounced to avoid firing too many events.
    const debounce = (func, delay) => {
        let timeoutId;
        return function(...args) {
            if (timeoutId) {
                clearTimeout(timeoutId);
            }
            timeoutId = setTimeout(() => {
                func.apply(this, args);
            }, delay);
        };
    };

    const setupDragAndDrop = () => {
        const draggables = document.querySelectorAll('.draggable-chart');
        draggables.forEach(el => {
            el.addEventListener('dragstart', e => {
                e.dataTransfer.setData('text/plain', el.id);
            });
        });

        const dropArea = document.getElementById('canvas-drop-area');
        if (dropArea) {
            // Using event delegation for drop cells
            dropArea.addEventListener('dragover', e => {
                e.preventDefault();
                const dropCell = e.target.closest('.drop-cell');
                if (dropCell) {
                    dropCell.classList.add('drag-over');
                }
            });

            dropArea.addEventListener('dragleave', e => {
                const dropCell = e.target.closest('.drop-cell');
                if (dropCell) {
                    dropCell.classList.remove('drag-over');
                }
            });

            dropArea.addEventListener('drop', e => {
                e.preventDefault();
                const dropCell = e.target.closest('.drop-cell');
                if (dropCell) {
                    dropCell.classList.remove('drag-over');
                    const chartId = e.dataTransfer.getData('text/plain');
                    const cellIndex = parseInt(dropCell.getAttribute('data-cell-index'), 10);

                    // Set props on the dcc.Store to trigger the server-side callback
                    dash_clientside.setProps('drop-data-store', {
                        data: {
                            chartId: chartId,
                            cellIndex: cellIndex
                        }
                    });
                }
            });
        }
    };

    // Use a MutationObserver to re-run the setup function when the DOM changes.
    // This is necessary because the drop cells are dynamically generated by Dash callbacks.
    const observer = new MutationObserver(debounce(setupDragAndDrop, 100));
    const targetNode = document.getElementById('canvas-drop-area');
    if (targetNode) {
        observer.observe(targetNode, { childList: true, subtree: true });
    }

    // Initial setup
    setupDragAndDrop();
});
